#!/usr/bin/env python3
"""Manifests the microcontrollers verify, in the three carriage forms.

For each algorithm one three-certificate hierarchy from the paper's builder
(src/pq_cose.py) and four COSE_Sign1 over the paper's claim:
  full   x5chain = [leaf, intermediate, root]  (root included, as the Adobe
         test chains do; C2PA 2.5 says it should not be)
  chain  x5chain = [leaf, intermediate]  (the conformant form; root from the
         device's trust store)
  leaf   x5chain = leaf only; issuers come from the device's trust store
  thumb  x5t = SHA-256 of the leaf; the leaf comes from the trust store too
The trust store (intermediate, root, and the known signer's leaf) is compiled
into the firmware as a verifier's would be. ES256 signatures are 64-byte r||s.

    python3 gen_vectors.py /path/to/line-a/src > vectors.h
"""
import sys
sys.path.insert(0, sys.argv[1])
from pq_cose import CLAIM, build_chain, sign_cose, sign_cose_certref  # noqa: E402

ALGS = ["Ed25519", "ES256", "ML-DSA-44", "ML-DSA-65", "ML-DSA-87"]  # PS256 has no MCU backend


def carr(name, data):
    return f"static const uint8_t {name}[{len(data)}] = {{{','.join(map(str, data))}}};\n"


out = ["/* generated by gen_vectors.py; do not edit */\n#include <stdint.h>\n#include <stddef.h>\n",
       carr("CLAIM", CLAIM)]
rows = []
for a in ALGS:
    key, chain = build_chain(a, 3)
    full, _ = sign_cose(a, key, chain, CLAIM, "root")
    chf, _ = sign_cose(a, key, chain, CLAIM, "chain")
    leaf, _ = sign_cose(a, key, chain, CLAIM, "leaf")
    thumb, _ = sign_cose_certref(a, key, chain, CLAIM)
    i = a.replace("-", "_")
    for nm, b in (("FULL", full), ("CHAIN", chf), ("LEAF", leaf), ("THUMB", thumb),
                  ("TS_LEAF", chain[0]), ("TS_MID", chain[1]), ("TS_ROOT", chain[2])):
        out.append(carr(f"{nm}_{i}", b))
    rows.append((a, i, len(full), len(chf), len(leaf), len(thumb), [len(c) for c in chain]))
out.append("""typedef struct {
  const char *alg;
  const uint8_t *full; size_t full_len;
  const uint8_t *chain; size_t chain_len;
  const uint8_t *leaf; size_t leaf_len;
  const uint8_t *thumb; size_t thumb_len;
  const uint8_t *ts_leaf; size_t ts_leaf_len;
  const uint8_t *ts_mid; size_t ts_mid_len;
  const uint8_t *ts_root; size_t ts_root_len;
} vec_t;
static const vec_t VECTORS[] = {
""")
for a, i, *_ in rows:
    out.append(f'  {{"{a}", FULL_{i}, sizeof FULL_{i}, CHAIN_{i}, sizeof CHAIN_{i}, '
               f'LEAF_{i}, sizeof LEAF_{i}, '
               f'THUMB_{i}, sizeof THUMB_{i}, TS_LEAF_{i}, sizeof TS_LEAF_{i}, '
               f'TS_MID_{i}, sizeof TS_MID_{i}, TS_ROOT_{i}, sizeof TS_ROOT_{i}}},\n')
out.append(f"}};\n#define N_VECTORS {len(rows)}\n")
for a, i, f, ch, l, t, c in rows:
    out.append(f"/* {a}: full {f} B, chain {ch} B, leaf-only {l} B, thumbprint {t} B, "
               f"certificates {c} */\n")
sys.stdout.write("".join(out))
